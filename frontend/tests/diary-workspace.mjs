import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = 'http://127.0.0.1:18080'
const output = new URL('../../docs/design/diary-workspace/', import.meta.url)
await fs.mkdir(output, { recursive: true })
async function api(path, method = 'GET', body) {
  const r = await fetch(`${base}/api${path}`, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) })
  assert(r.ok, `${method} ${path}: ${r.status}`); return r.json()
}
const original = await api('/settings')
const ids = []
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1363, height: 871 } })
const errors = []
page.on('pageerror', e => errors.push(e.message))
try {
  await api('/settings', 'PATCH', { onboarding_complete: true, save_enabled: true })
  const longText = '独立滚动验收长篇：' + '今天沿着校园走了很久，把一天的感受慢慢记下来。\n'.repeat(65)
  for (let i = 0; i < 28; i++) ids.push((await api('/diaries', 'POST', { text: i === 27 ? longText : `分栏回归虚构日记 ${i + 1}：普通的一天。` })).id)
  await page.goto(base)
  await page.getByRole('button', { name: '日记', exact: true }).click()
  await page.getByRole('tab', { name: '日记列表', exact: true }).click()
  assert.equal(await page.locator('.journal-composer').count(), 0, 'List must not contain the writing form')
  await page.locator('.diary-row').filter({ hasText: '独立滚动验收长篇' }).click()
  const list = page.locator('.diary-list'), detail = page.locator('.diary-detail-pane')
  await page.locator('.diary-layout').scrollIntoViewIfNeeded()
  const state = () => page.evaluate(() => ({ list: document.querySelector('.diary-list').scrollTop, detail: document.querySelector('.diary-detail-pane').scrollTop, document: scrollY }))
  const a = await state()
  let box = await list.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + 50); await page.mouse.wheel(0, 280)
  await page.waitForFunction(value => document.querySelector('.diary-list').scrollTop > value, a.list)
  const b = await state()
  assert.equal(b.detail, a.detail); assert.equal(b.document, a.document)
  box = await detail.boundingBox()
  await page.mouse.move(box.x + box.width / 2, box.y + 70); await page.mouse.wheel(0, 300)
  await page.waitForFunction(value => document.querySelector('.diary-detail-pane').scrollTop > value, b.detail)
  const c = await state()
  assert.equal(c.list, b.list); assert.equal(c.document, b.document)
  await page.screenshot({ path: fileURLToPath(new URL('1363-independent-scroll.png', output)) })
  await page.getByRole('button', { name: '＋ 写日记', exact: true }).click()
  assert.equal(await page.locator('.diary-list-pane').count(), 0)
  assert.equal(await page.locator('.diary-detail-pane').count(), 0)
  const draft = '独立写作回归：只属于新日记的草稿。'
  await page.locator('#journal-draft').fill(draft)
  await page.getByRole('button', { name: '返回日记列表', exact: true }).click()
  await page.locator('.diary-row').filter({ hasText: '独立滚动验收长篇' }).click()
  await page.getByRole('button', { name: '编辑记录', exact: true }).click()
  await page.locator('#diary-original').fill('独立滚动验收长篇：编辑后的旧记录。')
  await page.getByRole('button', { name: '保存修改', exact: true }).click()
  await page.locator('.entry-original').filter({ hasText: '编辑后的旧记录' }).waitFor()
  await page.locator('#diary-supplement').fill('后来补充也独立保存。')
  await page.getByRole('button', { name: '添加补充', exact: true }).click()
  await page.locator('.addendum').waitFor()
  await page.getByRole('button', { name: '＋ 写日记', exact: true }).click()
  assert.equal(await page.locator('#journal-draft').inputValue(), draft)
  await page.screenshot({ path: fileURLToPath(new URL('1363-writer.png', output)) })
  await page.route('**/api/diaries', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, body: 'test failure' }) : route.continue())
  await page.getByRole('button', { name: '保存日记', exact: true }).click()
  await page.getByRole('alert').waitFor()
  assert.equal(await page.locator('#journal-draft').inputValue(), draft)
  await page.unroute('**/api/diaries')
  await page.getByRole('button', { name: '保存日记', exact: true }).click()
  await page.locator('.entry-original').filter({ hasText: draft }).waitFor()
  const created = (await api('/diaries')).items.filter(d => d.text === draft)
  assert.equal(created.length, 1); ids.push(created[0].id)
  await page.getByRole('button', { name: '＋ 写日记', exact: true }).click()
  await page.locator('#journal-draft').fill('独立写作回归：先听回应，再确认保存。')
  await page.getByRole('radio', { name: '需要回应', exact: true }).check()
  await page.route('**/api/companion/respond', route => route.fulfill({ json: { reply: '你可以慢慢记下来。' } }))
  await page.getByRole('button', { name: '先听听心栖回应', exact: true }).click()
  await page.getByTestId('diary-response-preview').waitFor()
  await page.getByRole('button', { name: '保存这篇日记', exact: true }).click()
  await page.locator('.diary-response-entry').waitFor()
  const responseDiary = (await api('/diaries')).items.find(d => d.text === '独立写作回归：先听回应，再确认保存。')
  assert.equal(responseDiary.response_text, '你可以慢慢记下来。'); ids.push(responseDiary.id)
  for (const width of [390, 781]) {
    await page.setViewportSize({ width, height: 871 })
    assert(!(await page.locator('.diary-list-pane').isVisible()))
    await page.getByRole('button', { name: '← 返回所有记录', exact: true }).click()
    assert(!(await detail.isVisible())); assert(await list.isVisible())
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-list.png`, output)) })
    await page.locator('.diary-row').filter({ hasText: '先听回应，再确认保存' }).click()
    assert(!(await page.locator('.diary-list-pane').isVisible()))
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-detail.png`, output)) })
  }
  assert.deepEqual(errors, [])
  await fs.writeFile(new URL('results.json', output), JSON.stringify({ passed: true, checks: ['independent wheel scroll without document chaining', 'standalone writing page', 'draft preserved through old-entry edit/addendum', 'save failure and retry', 'save original and model response', 'mobile/tablet list-detail navigation'], errors }, null, 2))
  console.log('PASS separate writer, independent pane scrolling, edit/addendum/draft/retry, mobile and tablet navigation')
} finally {
  for (const id of ids) await api(`/diaries/${id}`, 'DELETE')
  await api('/settings', 'PATCH', original)
  await browser.close()
}
