import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const base='http://127.0.0.1:18080', out='../docs/design/floating-tools'
await fs.mkdir(out,{recursive:true})
const api=async(path,method='GET',body)=>{const r=await fetch(`${base}/api${path}`,{method,headers:{'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});assert(r.ok);return r.json()}
const original=await api('/settings'),before=await api('/diaries')
const browser=await chromium.launch({channel:'msedge',headless:true}), page=await browser.newPage({viewport:{width:793,height:871}}),errors=[],checks=[]
page.on('pageerror',e=>errors.push(e.message))
try{
 await api('/settings','PATCH',{onboarding_complete:true})
 await page.goto(base)
 const entry=page.getByRole('button',{name:'打开陪伴工具',exact:true})
 await entry.waitFor()
 assert.equal(await entry.evaluate(el=>getComputedStyle(el).position),'fixed','tools entry must float independently of header')
 const header=await page.locator('.nature-topline').boundingBox()
 let box=await entry.boundingBox()
 assert(box.y>=header.y+header.height,'initial button must be below header')
 await page.screenshot({path:`${out}/793-initial.png`})
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+130,box.y+150,{steps:12});await page.mouse.up()
 const moved=await entry.boundingBox()
 assert(moved.x>box.x+60 && moved.y>box.y+60,'drag moves floating entry')
 assert.equal(await page.locator('dialog[open]').count(),0,'drag must not open drawer')
 await entry.click();await page.getByRole('dialog',{name:'陪伴工具',exact:true}).waitFor();await page.keyboard.press('Escape')
 assert.equal(await page.locator('.conversation-scroll').textContent(), '我喜欢安静地听你说话。你想办法的时候，我也可以陪你一起想。从一件小事开始也可以。')
 await page.getByRole('button',{name:'我的',exact:true}).click()
 const other=await page.locator('.nature-topline').boundingBox()
 assert.equal(header.height,other.height);assert.equal(header.x,other.x)
 await page.getByRole('button',{name:'陪伴',exact:true}).click()
 box=await entry.boundingBox();assert(Math.abs(box.x-moved.x)<2 && Math.abs(box.y-moved.y)<2)
 checks.push('floating drag/click distinction, header consistency, cross-page position')
 await page.getByRole('button',{name:'想放松一下',exact:true}).click();await page.getByRole('button',{name:'暂时不选',exact:true}).click()
 assert.equal(await page.locator('.save-only-confirmation').count(),0)
 await page.locator('#chat-message').fill('我今天有点累，想缓一缓。');await page.getByRole('button',{name:'发送',exact:true}).click()
 await page.waitForFunction(()=>!document.querySelector('.typing-state'))
 await page.getByRole('button',{name:'给我一个小建议',exact:true}).click()
 await page.waitForFunction(()=>!document.querySelector('.typing-state'))
 await page.locator('.user-message').filter({hasText:'给我一个小建议'}).waitFor()
 const card=page.getByTestId('advice-card').last(),old=await card.locator('h3').textContent()
 await card.getByRole('button',{name:'换个更轻松的',exact:true}).click()
 await page.locator('.user-message').filter({hasText:'换一个更轻松的'}).waitFor()
 await page.waitForFunction(()=>document.querySelectorAll('[data-testid=advice-card]').length===2)
 assert.equal(await page.getByTestId('advice-card').first().locator('h3').textContent(),old)
 await page.getByTestId('advice-card').last().getByRole('button',{name:'先不用',exact:true}).click()
 await page.getByTestId('advice-card').last().getByText('这次先不做，没关系。',{exact:true}).waitFor()
 assert.equal(await page.locator('.save-only-confirmation').count(),0)
 const userCount=await page.locator('.user-message').count()
 await page.getByRole('button',{name:'日记',exact:true}).click();await page.getByRole('button',{name:'陪伴',exact:true}).click()
 assert.equal(await page.locator('.user-message').count(),userCount)
 checks.push('ordinary actions are silent, agent requests visible as user turns, original advice and chat retained')
 await page.screenshot({path:`${out}/793-chat.png`})
 for(const width of [390,793,1100]){
  await page.setViewportSize({width,height:871})
  box=await entry.boundingBox();assert(box.x>=0 && box.x+box.width<=width && box.y>=0 && box.y+box.height<=871)
  await page.screenshot({path:`${out}/${width}-floating.png`})
 }
 await page.reload();box=await entry.boundingBox();assert(box.x>=0 && box.x+box.width<=1100)
 const touch=await browser.newContext({viewport:{width:390,height:871},hasTouch:true,isMobile:true})
 const mobile=await touch.newPage();await mobile.goto(base)
 const touchEntry=mobile.getByRole('button',{name:'打开陪伴工具',exact:true})
 await touchEntry.waitFor();const start=await touchEntry.boundingBox()
 await mobile.screenshot({path:`${out}/390-initial.png`})
 const cdp=await touch.newCDPSession(mobile)
 await mobile.evaluate(()=>{window.touchTrace=[]; for(const name of ['pointerdown','pointerup','pointercancel','click'])document.addEventListener(name,e=>window.touchTrace.push({type:e.type,primary:e.isPrimary,button:e.button,detail:e.detail,x:e.clientX,y:e.clientY,target:e.target.closest('button')?.getAttribute('aria-label')}),true)})
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:start.x+24,y:start.y+25,id:1}]})
 for(let n=1;n<=8;n++) await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:start.x+24-100*n/8,y:start.y+25+100*n/8,id:1}]})
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 const end=await touchEntry.boundingBox();assert(end.x<start.x-60 && end.y>start.y+60)
 assert.equal(await mobile.locator('dialog[open]').count(),0)
 await touchEntry.tap()
 try { await mobile.getByRole('dialog',{name:'陪伴工具',exact:true}).waitFor({timeout:3000}) }
 catch(e){await mobile.screenshot({path:`${out}/touch-failure.png`});console.log(await mobile.evaluate(()=>window.touchTrace));throw e}
 await touch.close();checks.push('real touch gesture moves button without opening, tap opens drawer')
 assert.deepEqual(await api('/diaries'),before);assert.deepEqual(errors,[])
 await fs.writeFile(`${out}/results.json`,JSON.stringify({passed:true,checks,errors},null,2));console.log('PASS',checks)
}finally{await api('/settings','PATCH',original);await browser.close()}
