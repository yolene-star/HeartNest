import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = 'http://127.0.0.1:18080'
const out = new URL('../../docs/demo/', import.meta.url)
await fs.mkdir(out, { recursive: true })
const r = await fetch(`${base}/api/health`)
assert(r.ok)
assert.equal((await r.json()).diaries, 0, 'Record only in a fresh isolated demo database')
const browser = await chromium.launch({ channel: 'msedge', headless: true, slowMo: 180 })
const context = await browser.newContext({ viewport: { width: 1366, height: 900 }, recordVideo: { dir: fileURLToPath(out), size: { width: 1366, height: 900 } } })
const page = await context.newPage()
const recording = page.video()
const result = { passed: false, mode: 'offline-rules', description: '实际网页无声操作录屏；只使用模拟内容，不冒充真实模型演示。', errors: [] }
page.on('pageerror', error => result.errors.push(error.message))
const pause = () => page.waitForTimeout(1400)
try {
  await page.goto(base)
  await page.getByRole('button', { name: /认识 沐沐/ }).click()
  await page.locator('#nickname').fill('小栖（演示）')
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await page.getByLabel('允许心栖在聊天时查找旧日记').check()
  await pause()
  await page.getByRole('button', { name: '完成设置', exact: true }).click()
  await page.locator('#chat-message').fill('今天做完展示很开心，想在校园散步放松一下。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.getByTestId('assistant-reply').waitFor()
  await page.locator('.emotion-prompt summary').click()
  await page.getByRole('button', { name: '差不多', exact: true }).click()
  await page.locator('.composer-settings summary').click()
  await page.getByLabel('同时保存心栖回应').check()
  await page.locator('.composer-settings summary').click()
  await page.getByRole('button', { name: '加入 Agent 记忆库', exact: true }).click()
  await page.getByText('已加入 Agent 记忆库', { exact: true }).waitFor()
  await pause()
  await page.getByRole('button', { name: '给我一个小建议', exact: true }).click()
  const advice = page.getByTestId('advice-card')
  await advice.getByRole('button', { name: '依据与适用范围', exact: true }).click()
  await pause()
  await page.getByRole('button', { name: '一起找个小活动', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.typing-state'))
  await page.locator('#chat-message').fill('我想周末在校园散步，预算是零元。')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.typing-state'))
  await pause()
  await page.getByRole('button', { name: '我的', exact: true }).click()
  await page.locator('.profile-settings').scrollIntoViewIfNeeded()
  await pause()
  await page.getByRole('button', { name: '日记', exact: true }).click()
  await page.locator('.calendar-toolbar strong').waitFor()
  const day = new Date().getDate()
  await page.locator('.calendar-cell').filter({ has: page.locator('.calendar-number', { hasText: new RegExp(`^${day}$`) }) }).click()
  await page.getByRole('button', { name: '打开这篇日记', exact: true }).click()
  await page.locator('#diary-supplement').fill('后来补充：把完成的事情记下来，也是一种照顾自己。')
  await page.getByRole('button', { name: '添加补充', exact: true }).click()
  await page.locator('.addendum').waitFor()
  await pause()
  await page.getByRole('switch', { name: '允许这篇记录用于记忆检索' }).click()
  await pause()
  await page.getByRole('button', { name: '回顾', exact: true }).click()
  await page.getByTestId('mood-timeline').scrollIntoViewIfNeeded()
  await pause()
  assert.deepEqual(result.errors, [])
  await page.screenshot({ path: fileURLToPath(new URL('final-frame.png', out)), fullPage: true })
  result.passed = true
} catch (error) { result.failure = error.stack; process.exitCode = 1 }
finally {
  await context.close()
  await recording.saveAs(fileURLToPath(new URL('heartnest-demo.webm', out)))
  await fs.unlink(await recording.path()).catch(() => {})
  await browser.close()
  result.video_bytes = (await fs.stat(new URL('heartnest-demo.webm', out))).size
  await fs.writeFile(new URL('recording.json', out), JSON.stringify(result, null, 2))
  console.log(JSON.stringify(result, null, 2))
}
