import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const base = 'http://127.0.0.1:18080'
const output = new URL('../../docs/design/relaxation-validation/', import.meta.url)
await fs.mkdir(output, { recursive: true })
async function api(path, method = 'GET', body) {
  const r = await fetch(`${base}/api${path}`, { method, headers: { 'Content-Type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) })
  assert(r.ok, `${path}: ${r.status}`)
  return r.json()
}
const settings = await api('/settings')
const before = await api('/diaries'), profiles = await api('/profile')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = [], checks = []
page.on('pageerror', e => errors.push(e.message))
const chooser = page.getByRole('dialog', { name: '现在更想怎么缓一缓？' })
const invitation = page.getByTestId('relaxation-invitation')
async function send(text) {
  const count = await page.getByTestId('assistant-reply').count()
  await page.locator('#chat-message').fill(text)
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await page.waitForFunction(n => document.querySelectorAll('[data-testid="assistant-reply"]').length > n, count, { timeout: 60000 })
  await page.getByRole('button', { name: '发送', exact: true }).waitFor()
}
try {
  await api('/settings', 'PATCH', { onboarding_complete: true, pet_id: 'otter' })
  await page.goto(base)
  await page.getByRole('button', { name: '想放松一下', exact: true }).click({ timeout: 5000 })
  await chooser.waitFor()
  await page.keyboard.press('Escape')
  assert(!(await chooser.isVisible()))
  assert(await page.getByRole('button', { name: '想放松一下', exact: true }).evaluate(el => el === document.activeElement))
  await send('今天很累，但还没想好要做什么。')
  assert.equal(await invitation.count(), 0)
  await send('我想放松一下。')
  await invitation.waitFor()
  await invitation.scrollIntoViewIfNeeded()
  await page.screenshot({ path: fileURLToPath(new URL('invitation.png', output)) })
  await invitation.getByRole('button', { name: '先不用', exact: true }).click()
  await send('现在我想休息一会儿。')
  assert.equal(await invitation.count(), 0)
  checks.push('manual entry, Escape/focus return, explicit request only, one invitation and refusal respected')
  await page.reload()
  await send('我想放松一下。')
  await invitation.getByRole('button', { name: '看看放松方式' }).click()
  await chooser.getByRole('button', { name: /去湖边坐坐/ }).click()
  await page.getByTestId('quiet-scene').waitFor()
  await page.getByRole('button', { name: '返回陪伴', exact: true }).click()
  assert.equal(await page.getByTestId('assistant-reply').count(), 1)
  checks.push('acceptance enters real lake, returning preserves conversation')
  await page.getByRole('button', { name: '想放松一下', exact: true }).click()
  await chooser.getByRole('button', { name: /试个小办法/ }).click()
  await page.getByTestId('advice-card').waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: '依据与适用范围', exact: true }).click()
  assert.match(await page.locator('.evidence-detail a').getAttribute('href'), /who.int/)
  checks.push('optional practice uses actual API and expandable WHO source')
  for (const width of [390, 785, 1440]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 900 })
    await page.locator('.welcome-strip').scrollIntoViewIfNeeded()
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-home.png`, output)) })
    assert(await page.getByRole('button', { name: '想放松一下', exact: true }).evaluate(b => { const r = b.getBoundingClientRect(); return document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)?.closest('button') === b }))
    await page.getByRole('button', { name: '想放松一下', exact: true }).click()
    const r = await chooser.boundingBox()
    assert(r.x >= 0 && r.x + r.width <= width)
    assert(await chooser.getByRole('button', { name: '继续聊聊', exact: true }).evaluate(b => { const r = b.getBoundingClientRect(); return document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)?.closest('button') === b }))
    await page.screenshot({ path: fileURLToPath(new URL(`${width}-choices.png`, output)) })
    await chooser.getByRole('button', { name: '继续聊聊', exact: true }).click()
    assert(await page.locator('#chat-message').evaluate(el => el === document.activeElement))
  }
  checks.push('390/785/1440 visible choices, usable controls, continue chatting focuses composer')
  for (const text of ['我不想放松，只想吐槽，不用建议。', '我以前说过想休息吗？']) {
    await page.reload()
    await send(text)
    assert.equal(await invitation.count(), 0)
  }
  // A later explicit practice choice overrides the earlier listen-only choice.
  await send('我只想吐槽，不用建议。')
  await page.getByRole('button', { name: '想放松一下', exact: true }).click()
  await chooser.getByRole('button', { name: /试个小办法/ }).click()
  await page.getByTestId('advice-card').waitFor({ timeout: 60000 })
  await page.getByRole('button', { name: '换个更轻松的', exact: true }).click()
  await page.getByText('换了一种练习，你可以看看是否适合。', { exact: true }).waitFor()
  await page.reload()
  await page.route('**/api/companion/respond', route => route.fulfill({ json: { reply: '先关注此刻的安全和现实支持。', safety: true, intent: 'share', memories: [] } }))
  await send('我想放松一下。')
  assert.equal(await invitation.count(), 0)
  await page.unroute('**/api/companion/respond')
  await page.reload()
  await page.route('**/api/companion/respond', route => route.fulfill({ status: 503, body: 'unavailable' }))
  await page.getByRole('button', { name: '想放松一下', exact: true }).click()
  await chooser.getByRole('button', { name: /试个小办法/ }).click()
  await page.getByRole('alert').filter({ hasText: '回应暂时没有送达' }).waitFor()
  await page.unroute('**/api/companion/respond')
  await page.getByRole('button', { name: '想放松一下', exact: true }).click()
  await chooser.getByRole('button', { name: /试个小办法/ }).click()
  await page.getByTestId('advice-card').waitFor({ timeout: 60000 })
  assert.deepEqual(await api('/diaries'), before)
  assert.deepEqual(await api('/profile'), profiles)
  assert.deepEqual(errors, [])
  checks.push('listen-only/history have no invitation; no automatic diary or interest persistence')
  checks.push('changed preference honored, alternative practice works, safety suppresses invitation, failed API can retry')
  await fs.writeFile(new URL('results.json', output), JSON.stringify({ passed: true, checks, errors }, null, 2))
  console.log(`PASS ${checks.length} relaxation flow scenarios`)
} finally {
  await api('/settings', 'PATCH', settings)
  await browser.close()
}
